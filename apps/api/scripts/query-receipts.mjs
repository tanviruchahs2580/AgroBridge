#!/usr/bin/env node
/**
 * EXPLAIN receipt generator (ARC-15): runs EXPLAIN QUERY PLAN for the hot read
 * families against the suite's SQLite database (prisma/test.db, prepared by the
 * test global setup) and prints a committed receipt.
 *
 * Usage: node scripts/query-receipts.mjs   (from apps/api, after test setup)
 * Reproduce on PostgreSQL for the production plan: same statements against the
 * Neon database — the receipt file records the environment it was captured on.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const { PrismaClient } = require("@prisma/client");

const prisma = new PrismaClient();

const HOT_QUERY_PLANS = [
  ["products list: isActive filter + newest-first + LIMIT cap", 'SELECT * FROM "Product" WHERE "isActive" = 1 ORDER BY "createdAt" DESC LIMIT 12'],
  ["notifications: unread critical count per user", 'SELECT COUNT(*) FROM "Notification" WHERE "userId" = :user AND "readAt" IS NULL AND "category" = :cat'],
  ["wallet: ledger sum per user (reconciler hot path)", 'SELECT SUM("amountPaisa") FROM "WalletTransaction" WHERE "userId" = :user AND "direction" = :dir'],
  ["orders: capped newest-first per user", 'SELECT * FROM "Order" WHERE "userId" = :user ORDER BY "createdAt" DESC LIMIT 20'],
  ["farm events: per farm, newest first", 'SELECT * FROM "FarmEvent" WHERE "farmId" = :farm ORDER BY "occurredAt" DESC LIMIT 50'],
];

const out = [];
let ok = true;
for (const [label, sql] of HOT_QUERY_PLANS) {
  // Named placeholders bound to real values — no self-replacement chains.
  const bound = sql
    .replaceAll(":user", "'u1'")
    .replaceAll(":cat", "'CRITICAL'")
    .replaceAll(":dir", "'CREDIT'")
    .replaceAll(":farm", "'f1'") ;
  try {
    const plan = await prisma.$queryRawUnsafe(`EXPLAIN QUERY PLAN ${bound}`);
    const details = plan.map((r) => r.detail ?? r.id).join(" | ");
    out.push(`### ${label}\n\n\`\`\`sql\n${bound}\n\`\`\`\n\n\`\`\`\n${details}\n\`\`\`\n`);
  } catch (e) {
    ok = false;
    out.push(`### ${label}\n\nFAILED: ${e.message}\n`);
  }
}

const receiptPath = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..", "..", "docs", "qa", "query-plan-receipt.md");
writeFileSync(receiptPath, `# Query plan receipt (ARC-15)\n\nGenerated by \`apps/api/scripts/query-receipts.mjs\` against the SQLite suite database\n(\`prisma/test.db\` after the test global setup). Plans are engine-specific — PostgreSQL\nplans for the production database must be captured separately (owner's database).\n\n${out.join("\n")}`);
console.log(`query plan receipt written: ${receiptPath} (${ok ? "all plans ok" : "SOME FAILED"})`);
await prisma.$disconnect();
process.exit(ok ? 0 : 1);
